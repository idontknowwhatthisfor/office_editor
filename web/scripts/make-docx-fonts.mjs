// Regenerates src/docx/fonts.css: @font-face rules that make open, metric-compatible fonts answer
// to the names of the proprietary fonts Word documents ask for, so lines and pages break where
// they do in Word. Android has none of these fonts. No local() source: it names one face, so it
// would serve the regular face for bold and italic too. Run after changing the list or updating
// @fontsource packages:  node scripts/make-docx-fonts.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const web = join(dirname(fileURLToPath(import.meta.url)), '..');
// Word font -> metric-compatible replacement (@fontsource package name).
const fonts = { 'Times New Roman': 'tinos', Arial: 'arimo', Calibri: 'carlito' };
const subsets = ['latin', 'latin-ext'];

let css = '/* Generated by scripts/make-docx-fonts.mjs; do not edit. */\n';
for (const [family, pkg] of Object.entries(fonts)) {
  for (const variant of ['400', '400-italic', '700', '700-italic']) {
    const source = readFileSync(join(web, 'node_modules/@fontsource', pkg, `${variant}.css`), 'utf8');
    for (const block of source.split('/* ').slice(1)) {
      const subset = block.match(new RegExp(`^${pkg}-(.+?)-\\d+-`))[1];
      if (!subsets.includes(subset)) continue;
      const get = (prop) => block.match(new RegExp(`${prop}: ([^;]+);`))[1];
      const file = block.match(/url\(\.\/(files\/[^)]+\.woff2)\)/)[1];
      css += `
@font-face {
  font-family: '${family}';
  font-style: ${get('font-style')};
  font-weight: ${get('font-weight')};
  src: url(../../node_modules/@fontsource/${pkg}/${file}) format('woff2');
  unicode-range: ${get('unicode-range')};
}
`;
    }
  }
}
writeFileSync(join(web, 'src/docx/fonts.css'), css);
