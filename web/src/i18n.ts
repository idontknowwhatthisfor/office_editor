const strings = /^(id|in)\b/i.test(navigator.language) ? id : en;

export function t(key: keyof typeof en, params: Record<string, string | number> = {}): string {
  return strings[key].replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? ''));
}
